_CJK_CHAR_RE = re.compile(r"[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7af]")


def resolve_language(preferred: str | None = None) -> str:
    """Resolve UI locale from explicit preference, env, or OS locale (defaulting to 'en')."""
    raw = (preferred or os.getenv("AXONPG_LANG", "auto")).strip().lower()
    if raw and raw != "auto":
        short = raw.split("_")[0].split("-")[0]
        if short in SUPPORTED_LANGUAGES:
            return short

    sys_loc = locale.getlocale()[0] or os.getenv("LANG", "")
    short_sys = sys_loc.lower().split("_")[0].split("-")[0]
    return short_sys if short_sys in SUPPORTED_LANGUAGES else "en"


def t(key: str, lang: str = "en", **kwargs: Any) -> str:
    """Translate a message key with safe fallback to English and optional format interpolation."""
    catalog = _MESSAGES.get(lang, _MESSAGES["en"])
    template = catalog.get(key) or _MESSAGES["en"].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template


def normalize_unicode(text: str | None) -> str:
    """Return canonical NFC Unicode string without dropping non-Latin scripts."""
    if not text:
        return ""
    return unicodedata.normalize("NFC", text).strip()


def fold_accents_preserving_scripts(text: str) -> str:
    """Strip Latin combining diacritics while preserving Japanese dakuten, Hangul, Arabic, and Cyrillic."""
    decomposed = unicodedata.normalize("NFD", text)
    stripped = "".join(
        ch
        for ch in decomposed
        if not (unicodedata.category(ch) == "Mn" and 0x0300 <= ord(ch) <= 0x036F)
    )
    return unicodedata.normalize("NFC", stripped)


def normalize_lookup_key(text: str | None) -> str:
    """
    Build a language-agnostic lookup key for entity/fact matching.

    Preserves Unicode letters across all scripts (Latin, CJK, Arabic, Cyrillic),
    folds diacritics and case (`Ventilación` == `ventilacion`), and collapses punctuation.
    """
    if not text:
        return ""
    folded = fold_accents_preserving_scripts(unicodedata.normalize("NFKC", text)).casefold()
    cleaned = re.sub(r"[^\w]+", "_", folded, flags=re.UNICODE).strip("_")
    return cleaned


def extract_search_tokens(text: str | None) -> list[str]:
    """
    Extract multilingual search tokens for keyword / FTS fallback.

    Keeps words >= 2 chars across Unicode scripts plus bigrams/characters for CJK text
    that does not separate words with spaces.
    """
    if not text:
        return []
    folded = fold_accents_preserving_scripts(unicodedata.normalize("NFKC", text)).casefold()
    tokens: list[str] = []
    seen: set[str] = set()

    for word in re.findall(r"\w+", folded, flags=re.UNICODE):
        if _CJK_CHAR_RE.search(word):
            # Include whole chunk plus 2-char shingles for CJK substring recall
            if word not in seen:
                tokens.append(word)
                seen.add(word)
            for idx in range(len(word) - 1):
                bigram = word[idx : idx + 2]
                if bigram not in seen:
                    tokens.append(bigram)
                    seen.add(bigram)
        elif len(word) >= 2 and word not in seen:
            tokens.append(word)
            seen.add(word)
    return tokens
